"""Fixed dev/holdout split of the images, saved to data/splits.json.

Reads file names only, never ground truth.
The inner loop evaluates on `dev`; `holdout` is used once, by `run.py --final`.

    uv run python -m src.splits   # writes data/splits.json from the dataset in config.yaml
"""

import argparse
import json
import random
import re
from pathlib import Path

SYNTHETIC = "90_SYNTHETIC_exact_ground_truth"
STEEL_316L = "02_316L_stainless_with_grain_masks/Grain"
STEEL_316L_FOLDER = {"dev": "val", "holdout": "test"}
TI64 = "01_BEST_Ti64_lamellar_bimodal/data"
TI64_LAMELLAR = [f"Ti64_{i}.jpg" for i in range(20, 40)]  # 0-19 are bimodal (equiaxed primary alpha), not flakes
DATASETS = ("synthetic", "316L", "lamellar_synth", "Ti64", "Ti64_scratched")
SEED = 0
HOLDOUT_FRACTION = 1 / 3
IMAGE_SUFFIXES = {".png", ".jpg", ".jpeg"}


def family(name: str) -> str:
    return re.sub(r"_\d+$", "", name)


def make_synthetic_split(names: list[str], seed: int = SEED) -> dict:
    """Per family, about 2/3 of the images go to dev and 1/3 to holdout.

    The magset* images are excluded: they come at 1.0 and 2.0 um/px,
    and their rows in the dataset have no mean grain size and no per-grain rows.
    """
    rng = random.Random(seed)
    excluded = sorted(n for n in names if n.startswith("magset"))
    by_family: dict[str, list[str]] = {}
    for n in sorted(set(names) - set(excluded)):
        by_family.setdefault(family(n), []).append(n)
    dev, holdout = [], []
    for fam in sorted(by_family):
        members = by_family[fam][:]
        rng.shuffle(members)
        k = round(len(members) * HOLDOUT_FRACTION)
        holdout += members[:k]
        dev += members[k:]
    return {"dev": sorted(dev), "holdout": sorted(holdout), "excluded": excluded}


def make_flake_splits(seed: int = SEED) -> dict:
    """lamellar_synth: per family of three, one image to holdout. Ti64: a third of the lamellar images to holdout.

    Both read names only: the synthetic names come from the generator's fixed list, the Ti64 names are fixed above.
    """
    from src.synth_lamellar import default_specs

    rng = random.Random(seed)
    by_family: dict[str, list[str]] = {}
    for spec in default_specs(seed):
        by_family.setdefault(spec.family, []).append(spec.name)
    synth = {"dev": [], "holdout": []}
    for fam in sorted(by_family):
        members = sorted(by_family[fam])
        out = rng.choice(members)
        synth["holdout"].append(out)
        synth["dev"] += [m for m in members if m != out]
    ti = TI64_LAMELLAR[:]
    rng.shuffle(ti)
    k = round(len(ti) * HOLDOUT_FRACTION)
    return {
        "lamellar_synth": {"dev": sorted(synth["dev"]), "holdout": sorted(synth["holdout"]),
                           "note": "code-generated by src/synth_lamellar.py (seed 0); one image per family held out"},
        "Ti64": {"dev": sorted(ti[k:]), "holdout": sorted(ti[:k]),
                 "note": "lamellar images Ti64_20 to Ti64_39 of Zenodo 5714384; Ti64_0 to Ti64_19 are bimodal and unused"},
    }


def make_splits(dataset_root: Path, seed: int = SEED) -> dict:
    synthetic = [p.stem for p in (dataset_root / SYNTHETIC / "corrupted").glob("*.png")]
    steel = {  # file names with extension: the 316L images are a mix of .png and .jpg
        split: sorted(p.name for p in (dataset_root / STEEL_316L / folder / "images").iterdir() if p.suffix in IMAGE_SUFFIXES)
        for split, folder in STEEL_316L_FOLDER.items()
    }
    return {
        "seed": seed,
        "synthetic": make_synthetic_split(synthetic, seed),
        "316L": {**steel, "note": "dev = the dataset's val folder, holdout = its test folder; train is unused"},
        **make_flake_splits(seed),
    }


def load(cfg: dict) -> dict:
    return json.loads(Path(cfg["paths"]["splits"]).read_text())


def image_paths(cfg: dict, dataset: str, split: str) -> list[Path]:
    """Paths of the input images of one split. Only images, never ground truth."""
    names = load(cfg)["Ti64" if dataset == "Ti64_scratched" else dataset][split]
    root = Path(cfg["paths"]["dataset"])
    if dataset == "synthetic":
        folder = root / SYNTHETIC / cfg["eval"]["synthetic_variant"]
        return [folder / f"{n}.png" for n in names]
    if dataset == "316L":
        folder = root / STEEL_316L / STEEL_316L_FOLDER[split] / "images"
        return [folder / n for n in names]
    if dataset == "lamellar_synth":
        from src.synth_lamellar import ensure

        folder = ensure(Path(cfg["paths"]["lamellar_synth"])) / "images"
        return [folder / f"{n}.png" for n in names]
    if dataset == "Ti64":
        return [root / TI64 / n for n in names]
    if dataset == "Ti64_scratched":  # scratched copies of the Ti64 images: same names, same split
        folder = Path(cfg["paths"]["Ti64_scratched"]) / "images"
        if not folder.exists():
            raise FileNotFoundError(f"{folder} missing: run python -m src.scratch_paste --src <Ti64 folder> once")
        return [folder / f"{Path(n).stem}.png" for n in load(cfg)["Ti64"][split]]
    raise ValueError(f"unknown dataset {dataset!r}, expected one of {DATASETS}")


def main(argv=None) -> None:
    from src.config import load_config

    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", default="config.yaml")
    parser.add_argument("--flakes-only", action="store_true",
                        help="add or refresh the flake datasets only, leaving the grain splits as they are")
    args = parser.parse_args(argv)
    cfg = load_config(args.config)
    out = Path(cfg["paths"]["splits"])
    if args.flakes_only:
        splits = {**json.loads(out.read_text()), **make_flake_splits()}
    else:
        splits = make_splits(Path(cfg["paths"]["dataset"]))
    out.write_text(json.dumps(splits, indent=2) + "\n")
    for d in DATASETS:
        print(f"{d}: dev {len(splits[d]['dev'])}, holdout {len(splits[d]['holdout'])} -> {out}")


if __name__ == "__main__":
    main()
